import { readdir, mkdir, writeFile } from "node:fs/promises";
import path from "node:path";

const root = path.resolve(import.meta.dir, "../../category");
const output = path.resolve(
  import.meta.dir,
  "../src/lib/generated-previews.ts",
);
const previews: string[] = [];

async function scan(directory: string, depth = 0) {
  if (depth > 4) return;
  const metadata = Bun.file(path.join(directory, "item.json"));
  if ((await metadata.exists()) && (await metadata.json()).hidden === true)
    return;
  for (const file of await readdir(directory, { withFileTypes: true })) {
    if (
      file.name.startsWith(".") ||
      ["node_modules", "dist", "build"].includes(file.name)
    )
      continue;
    const absolute = path.join(directory, file.name);
    if (file.isDirectory()) await scan(absolute, depth + 1);
    else if (file.isFile() && file.name === "preview.tsx")
      previews.push(absolute);
  }
}

await scan(root);
previews.sort();
await mkdir(path.dirname(output), { recursive: true });
const entries = previews.map((file) => {
  const modulePath = path
    .relative(path.dirname(output), file)
    .replaceAll(path.sep, "/")
    .replace(/\.tsx$/, "");
  const id = path.relative(root, path.dirname(file)).replaceAll(path.sep, "/");
  return `  ${JSON.stringify(id)}: () => import(${JSON.stringify(modulePath)}),`;
});
await writeFile(
  output,
  `// Generated by scripts/generate-previews.ts. Do not edit.\nimport type { ComponentType } from "react";\n\nexport const previews: Record<string, () => Promise<{ default: ComponentType }>> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`Registered ${previews.length} React previews.`);
